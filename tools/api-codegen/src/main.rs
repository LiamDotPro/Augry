// Usage: api-codegen <openapi.yaml> <out.rs>
use std::{env, fs, process::exit};

fn main() {
    let args: Vec<String> = env::args().skip(1).collect();
    let [spec_path, out_path] = args.as_slice() else {
        eprintln!("usage: api-codegen <openapi.yaml> <out.rs>");
        exit(2);
    };

    let text = fs::read_to_string(spec_path).unwrap_or_else(|e| fail(&format!("reading {spec_path}: {e}")));
    let mut spec: openapiv3::OpenAPI =
        serde_yaml::from_str(&text).unwrap_or_else(|e| fail(&format!("parsing {spec_path}: {e}")));
    raw_mixed_responses(&mut spec);

    let mut settings = progenitor::GenerationSettings::default();
    settings
        .with_interface(progenitor::InterfaceStyle::Positional)
        .with_tag(progenitor::TagStyle::Merged);
    let tokens = progenitor::Generator::new(&settings)
        .generate_tokens(&spec)
        .unwrap_or_else(|e| fail(&format!("generating client: {e}")));
    let mut file = syn::parse2(tokens).unwrap_or_else(|e| fail(&format!("parsing generated code: {e}")));
    syn::visit_mut::VisitMut::visit_file_mut(&mut BlockDocs, &mut file);

    let header = "// @generated by tools/api-codegen from libs/api-contract/openapi.yaml.\n\
                  // Do not edit. Regenerate with `npm run api:generate`.\n\n";
    fs::write(out_path, header.to_string() + &prettyplease::unparse(&file))
        .unwrap_or_else(|e| fail(&format!("writing {out_path}: {e}")));
    println!("wrote {out_path}");
}

// Progenitor needs one body type for all success responses of an operation,
// and one for all its error responses. Where an operation mixes types in a
// group (postAuthGithubToken: 200 signed in, 202 keep polling; the 409s that
// return the current document or process), that group becomes raw bytes and
// the caller decodes it by status. See src-tauri/src/cloud/mod.rs.
fn raw_mixed_responses(spec: &mut openapiv3::OpenAPI) {
    use openapiv3::{MediaType, ReferenceOr, Response, StatusCode};
    use std::collections::BTreeSet;

    let shared = spec.components.as_ref().map(|c| c.responses.clone()).unwrap_or_default();
    let resolve = |r: &ReferenceOr<Response>| -> Option<Response> {
        match r {
            ReferenceOr::Item(r) => Some(r.clone()),
            ReferenceOr::Reference { reference } => match shared.get(reference.rsplit('/').next()?)? {
                ReferenceOr::Item(r) => Some(r.clone()),
                _ => None,
            },
        }
    };
    let body_type = |r: &Response| -> String {
        match r.content.get("application/json").and_then(|m| m.schema.as_ref()) {
            Some(ReferenceOr::Reference { reference }) => reference.clone(),
            Some(ReferenceOr::Item(_)) => "inline".into(),
            None => "none".into(),
        }
    };

    for (path, item) in spec.paths.paths.iter_mut() {
        let ReferenceOr::Item(item) = item else { continue };
        let ops = [&mut item.get, &mut item.put, &mut item.post, &mut item.delete, &mut item.patch];
        for op in ops.into_iter().flatten() {
            for (group, in_group) in [
                ("success", (|c: &StatusCode| matches!(c, StatusCode::Code(200..=299))) as fn(&StatusCode) -> bool),
                ("error", |c: &StatusCode| matches!(c, StatusCode::Code(400..=599))),
            ] {
                let types: BTreeSet<String> = op
                    .responses
                    .responses
                    .iter()
                    .filter(|(c, _)| in_group(c))
                    .filter_map(|(_, r)| resolve(r).map(|r| body_type(&r)))
                    .collect();
                if types.len() < 2 {
                    continue;
                }
                for (_, r) in op.responses.responses.iter_mut().filter(|(c, _)| in_group(c)) {
                    let Some(mut inline) = resolve(r) else { continue };
                    inline.content.clear();
                    inline.content.insert("application/octet-stream".into(), MediaType::default());
                    *r = ReferenceOr::Item(inline);
                }
                let id = op.operation_id.as_deref().unwrap_or(path);
                eprintln!("note: {id} mixes {group} body types, its {group} responses are raw");
            }
        }
    }
}

// Multi-line docs print as /** */ blocks whose first line sits right after
// the opener while the rest is indented, so rustdoc reads the rest as code
// blocks and `cargo test` compiles them as doctests. Starting every
// multi-line doc on a new line indents all lines alike, which rustdoc strips.
struct BlockDocs;

impl syn::visit_mut::VisitMut for BlockDocs {
    fn visit_attribute_mut(&mut self, attr: &mut syn::Attribute) {
        if let syn::Meta::NameValue(nv) = &mut attr.meta {
            if nv.path.is_ident("doc") {
                if let syn::Expr::Lit(syn::ExprLit { lit: syn::Lit::Str(s), .. }) = &mut nv.value {
                    let text = s.value();
                    if text.contains('\n') && !text.starts_with('\n') {
                        *s = syn::LitStr::new(&format!("\n{text}"), s.span());
                    }
                }
            }
        }
    }
}

fn fail(msg: &str) -> ! {
    eprintln!("api-codegen: {msg}");
    exit(1);
}
